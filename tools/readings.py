"""Writes the search's per-character data, both committed beside the code that reads them:

  python tools/readings.py [Unihan.zip]

- `crates/novaplayer/src/app/query/readings.z`: every CJK ideograph of the Basic Multilingual
  Plane (URO, Extension A, compatibility) with its readings, zlib-compressed text, one line per
  character: the character, then its readings separated by spaces. Mandarin pinyin without tones
  (`ü` written both `v` and `u`; kMandarin, kHanyuPinyin, kXHC1983, kTGHZ2013), Cantonese
  jyutping without tones (kCantonese), Japanese readings in hiragana (kJapanese; the player
  romanises kana itself, by the same rule it romanises a song's kana with).
- `crates/novaplayer/src/app/query/latin.rs`: the Latin and Greek letters with marks, and the
  ligatures, each with the plain letters it is found by (`é` → `e`, `ß` → `ss`, `ά` → `α`).

The source is the Unihan database of Unicode 17.0.0 (Unicode License v3), downloaded and checked
against its SHA-256 unless a copy is given. The Latin table comes from Python's own Unicode data.
"""
import collections, hashlib, io, os, re, sys, unicodedata, urllib.request, zipfile, zlib

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "crates", "novaplayer", "src", "app", "query")
URL = "https://www.unicode.org/Public/17.0.0/ucd/Unihan.zip"
SHA256 = "f7a48b2b545acfaa77b2d607ae28747404ce02baefee16396c5d2d7a8ef34b5e"

HAN = [(0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF)]
MANDARIN = ["kMandarin", "kHanyuPinyin", "kXHC1983", "kTGHZ2013"]

# Letters no decomposition reaches, found by the plain letters a keyboard without them types.
LIGATURES = {
    "ß": "ss", "ẞ": "ss", "æ": "ae", "Æ": "ae", "œ": "oe", "Œ": "oe", "ø": "o", "Ø": "o",
    "đ": "d", "Đ": "d", "ð": "d", "Ð": "d", "þ": "th", "Þ": "th", "ł": "l", "Ł": "l",
    "ı": "i", "ŋ": "ng", "Ŋ": "ng", "ĸ": "k", "ſ": "s", "ƒ": "f", "ħ": "h", "Ħ": "h",
    "ŧ": "t", "Ŧ": "t", "ĳ": "ij", "Ĳ": "ij",
}
LATIN = [(0x00C0, 0x024F), (0x1E00, 0x1EFF), (0x0370, 0x03FF), (0x1F00, 0x1FFF)]


def unihan(path):
    if path:
        data = open(path, "rb").read()
    else:
        with urllib.request.urlopen(URL) as r:
            data = r.read()
    got = hashlib.sha256(data).hexdigest()
    if got != SHA256:
        sys.exit(f"Unihan.zip: SHA-256 {got}, expected {SHA256}")
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        return z.read("Unihan_Readings.txt").decode("utf-8")


def plain(s):
    s = unicodedata.normalize("NFD", s)
    return "".join(c for c in s if not unicodedata.combining(c))


def toneless(s):
    """Pinyin without its tone marks, `\u00fc` kept (`l\u01dc` \u2192 `l\u00fc`)."""
    s = unicodedata.normalize("NFD", s)
    s = "".join(c for c in s if not unicodedata.combining(c) or c == "\u0308")
    return unicodedata.normalize("NFC", s)


def hiragana(s):
    return "".join(chr(ord(c) - 0x60) if 0x30A1 <= ord(c) <= 0x30F6 else c for c in s)


def readings(text):
    fields = collections.defaultdict(dict)
    for line in text.splitlines():
        if line.startswith("#") or not line.strip():
            continue
        cp, field, value = line.split("\t")
        c = int(cp[2:], 16)
        if any(lo <= c <= hi for lo, hi in HAN):
            fields[c][field] = value
    lines = []
    for c in sorted(fields):
        f, out = fields[c], []

        def add(r):
            if r and r not in out:
                out.append(r)

        for k in MANDARIN:
            for tok in f.get(k, "").split():
                for r in tok.split(":")[-1].split(","):
                    r = toneless(r).lower()
                    add(r.replace("ü", "v"))
                    add(r.replace("ü", "u"))
        for r in f.get("kCantonese", "").split():
            add(re.sub(r"\d", "", r))
        for r in f.get("kJapanese", "").split():
            add(hiragana(r))
        if out:
            lines.append(chr(c) + " ".join(out))
    return "\n".join(lines) + "\n"


def latin():
    pairs = []
    for lo, hi in LATIN:
        for c in range(lo, hi + 1):
            ch = chr(c)
            if ch in LIGATURES:
                continue
            # The player lowercases before it looks a letter up: the lowercase letters only.
            if ch == ch.lower() and plain(ch) not in (ch, ""):
                pairs.append((ch, plain(ch)))
    pairs += [(c, b) for c, b in LIGATURES.items() if c == c.lower()]
    pairs = sorted(set(pairs), key=lambda p: ord(p[0]))
    body = "".join(f"    ('{c}', \"{b}\"),\n" for c, b in pairs)
    return (
        "//! Generated by `tools/readings.py` from Python's Unicode data; do not edit.\n"
        "//! Each Latin or Greek letter with marks, and each ligature, with the plain lowercase\n"
        "//! letters it is found by, sorted by the letter.\n\n"
        f"pub(super) const LATIN: [(char, &str); {len(pairs)}] = [\n{body}];\n"
    )


def main():
    text = readings(unihan(sys.argv[1] if len(sys.argv) > 1 else None))
    with open(os.path.join(OUT, "readings.z"), "wb") as f:
        f.write(zlib.compress(text.encode("utf-8"), 9))
    with open(os.path.join(OUT, "latin.rs"), "w", encoding="utf-8", newline="\n") as f:
        f.write(latin())
    print(f"{text.count(chr(10))} characters")


if __name__ == "__main__":
    main()
